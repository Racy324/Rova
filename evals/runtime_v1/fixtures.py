from __future__ import annotations

import hashlib
import shutil
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from uuid import uuid4


def _is_fixture_authority_file(source: Path, path: Path) -> bool:
    relative = path.relative_to(source)
    return (
        path.is_file()
        and "__pycache__" not in relative.parts
        and path.suffix not in {".pyc", ".pyo"}
    )


@dataclass(frozen=True)
class SmokeFixture:
    case_id: str
    source: Path

    @property
    def sha256(self) -> str:
        digest = hashlib.sha256()
        for path in sorted(item for item in self.source.rglob("*") if _is_fixture_authority_file(self.source, item)):
            digest.update(path.relative_to(self.source).as_posix().encode("utf-8"))
            digest.update(path.read_bytes())
        return digest.hexdigest()


def smoke_fixtures() -> tuple[SmokeFixture, ...]:
    root = Path(__file__).with_name("fixtures")
    return (
        SmokeFixture("CM01_fixture_probe", root / "cm01"),
        SmokeFixture("CM02_fixture_probe", root / "cm02"),
    )


def dry_run_context_fixtures() -> tuple[SmokeFixture, ...]:
    """Versioned source templates for the two non-formal Context dry-run cases.

    The large payloads are deterministically materialized into each fresh,
    disposable evaluation workspace.  The compact templates remain the
    immutable fixture authority in source control; their generated bytes are
    never derived from a model result or from an A/B outcome.
    """
    root = Path(__file__).with_name("fixtures")
    return (
        SmokeFixture("CM01_large_tool_output_repair", root / "cm01_dry"),
        SmokeFixture("CM02_long_history_followthrough", root / "cm02_dry"),
    )


@contextmanager
def fresh_workspace(
    fixture: SmokeFixture,
    root: Path,
    *,
    keep_failed: bool = False,
    failure_state: dict[str, bool] | None = None,
):
    """Copy one immutable fixture into an eval-owned workspace and clean it by default."""
    root = Path(root)
    workspace = root / f"{fixture.case_id}-{uuid4().hex}"
    shutil.copytree(
        fixture.source,
        workspace,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo"),
    )
    _materialize_pressure_fixture(fixture.case_id, workspace)
    try:
        yield workspace
    except BaseException:
        if keep_failed:
            raise
        shutil.rmtree(workspace, ignore_errors=True)
        try:
            root.rmdir()
        except OSError:
            pass
        raise
    else:
        # A deterministic validator failure is a failed evaluation outcome too.
        # The caller marks it before leaving the context after validation.
        if not (keep_failed and failure_state is not None and failure_state.get("failed", False)):
            shutil.rmtree(workspace, ignore_errors=True)
        try:
            root.rmdir()
        except OSError:
            pass


def _materialize_pressure_fixture(case_id: str, workspace: Path) -> None:
    """Expand only fixed evaluation templates after copying into a fresh root."""
    if case_id == "CM01_large_tool_output_repair":
        reference = workspace / "reference.txt"
        padding = "deterministic reference padding for Runtime V1 evaluation\n" * 1_600
        reference.write_text(
            padding + "ROVA_EVAL_TARGET_MAPPING=violet-47\n",
            encoding="utf-8",
            newline="\n",
        )
    elif case_id == "CM02_long_history_followthrough":
        constraints = workspace / "constraints"
        constraints.mkdir(parents=True, exist_ok=True)
        for index in range(1, 5):
            payload = (f"constraint-{index}: preserve the required constant across the final repair.\n" * 1_050)
            (constraints / f"constraint-{index}.txt").write_text(
                payload + f"ROVA_EVAL_CONSTRAINT_{index}=keep-violet-{index}\n",
                encoding="utf-8",
                newline="\n",
            )
